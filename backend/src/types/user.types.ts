/**
 * User types shared by controllers, services and repositories.
 *
 * They mirror the `User` model in prisma/schema.prisma but are declared as
 * plain interfaces so the service/controller layers stay independent of the
 * generated Prisma client. The repository is the only place the two meet.
 *
 * @author aliasgarbootwala3@gmail.com
 */

import type { UserRole } from "../constants/constants.js";
import type { BusinessSummary } from "./business.types.js";

/** A user as the API returns it. `password` is absent by design. */
export interface User {
  id: string;
  username: string;
  email: string;
  isDeleted: boolean;
  deletedAt: Date | null;
  tokenVersion: number;
  createdAt: Date;
  updatedAt: Date;
}

/** The one shape that carries the hash — only the login path may produce it. */
export interface UserWithPassword extends User {
  password: string;
}

/**
 * Columns written on insert. `password` must already be hashed, `id` is
 * generated by the database (cuid), and the audit columns are left to their
 * schema defaults.
 *
 * There is no `role`: the role belongs to the `BusinessMember` created in the
 * same transaction as the user.
 */
export interface CreateUserInput {
  username: string;
  email: string;
  password: string;
}

// ---------------------------------------------------------------------------
// Request-level DTOs (what the controller hands to the service)
// ---------------------------------------------------------------------------

/**
 * Public registration. There is no `role` field on purpose: the first account
 * of a business becomes its OWNER inside the service, and every later role is
 * assigned by an OWNER/ADMIN. A client can never self-assign a privileged role.
 */
export interface RegisterUserInput {
  username: string;
  email: string;
  password: string;
  /** Optional; defaults to a name derived from the username. */
  businessName?: string;
  /** ISO 3166-1 alpha-2, defaults to US. */
  country?: string;
}

export interface LoginUserInput {
  email: string;
  password: string;
}

export interface LogoutUserInput {
  token: string;
  userId: string;
}

export interface ProfileUserInput {
  userId: string;
  businessId: string;
  token: string;
}

// ---------------------------------------------------------------------------
// Response shapes
// ---------------------------------------------------------------------------

/** What the signed-in user sees. `role` is their role in `business`. */
export interface UserProfile {
  id: string;
  username: string;
  email: string;
  role: UserRole;
  business: BusinessSummary;
  createdAt: Date;
  updatedAt: Date;
}
